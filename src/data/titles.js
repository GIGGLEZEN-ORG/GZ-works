export const byId = (id) => TITLES.find((t) => t.id === id);

export const GENRES = Array.from(new Set(TITLES.flatMap((t) => t.genres))).sort();

export function buildRows(list = TITLES) {
  const inGenre = (g) => list.filter((t) => t.genres.includes(g));
  const rows = [
    { key: 'trending', title: 'Trending Now', items: list.filter((t) => t.trending) },
    { key: 'top10', title: 'Top 10 in India Today', items: list.filter((t) => t.top10).sort((a, b) => a.top10 - b.top10), top10: true },
    { key: 'new', title: 'New Releases', items: list.filter((t) => t.isNew) },
    { key: 'popular', title: 'Popular on JETIX', items: [...list].sort((a, b) => b.match - a.match) },
    { key: 'action', title: 'Action & Adventure', items: list.filter((t) => t.genres.some((g) => ['Action', 'Adventure', 'Heist'].includes(g))) },
    { key: 'thriller', title: 'Thrillers & Mysteries', items: list.filter((t) => t.genres.some((g) => ['Thriller', 'Mystery', 'Crime', 'Horror'].includes(g))) },
    { key: 'animation', title: 'Animation & Family', items: list.filter((t) => t.genres.some((g) => ['Animation', 'Kids', 'Family'].includes(g))) },
    { key: 'docs', title: 'Documentaries', items: inGenre('Documentary') },
    { key: 'scifi', title: 'Sci-Fi & Fantasy', items: list.filter((t) => t.genres.some((g) => ['Sci-Fi', 'Fantasy', 'Space'].includes(g))) },
    { key: 'cars', title: 'Fast Cars & Open Roads', items: inGenre('Automotive') },
    { key: 'drama', title: 'Dramas', items: inGenre('Drama') },
  ];
  return rows.filter((r) => r.items.length > 0);
}
