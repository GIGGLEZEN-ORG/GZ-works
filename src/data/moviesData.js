export function getCityTheaters(city = "mumbai") {
  if (!city) return cityTheaters["mumbai"];
  const raw = String(city).trim().toLowerCase();
  const normalized = raw.replace(/\s+/g, "-");
  
  const aliasMap = {
    "delhi": "delhi-ncr",
    "delhi-ncr": "delhi-ncr",
    "new-delhi": "delhi-ncr",
    "new delhi": "delhi-ncr",
    "ncr": "delhi-ncr",
    "bangalore": "bengaluru",
    "bengaluru": "bengaluru",
    "blr": "bengaluru",
    "hyderabad": "hyderabad",
    "hyd": "hyderabad",
    "mumbai": "mumbai",
    "bombay": "mumbai",
    "chennai": "chennai",
    "madras": "chennai",
    "kolkata": "kolkata",
    "calcutta": "kolkata",
    "pune": "pune",
    "ahmedabad": "ahmedabad",
    "amd": "ahmedabad",
    "chandigarh": "chandigarh",
    "jaipur": "jaipur"
  };

  const key = aliasMap[raw] || aliasMap[normalized] || raw;
  return (
    cityTheaters[key] ||
    cityTheaters[raw] ||
    cityTheaters[normalized] ||
    cityTheaters[normalized.replace(/-/g, " ")] ||
    cityTheaters["mumbai"]
  );
}

